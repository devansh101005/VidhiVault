ABSTAIN_MARKER = "i cannot find this information"
OUT_PATH = Path(__file__).resolve().parent / "manual_review.md"


def truncate(text: str, n: int) -> str:
    text = text.strip().replace("\n", " ")
    if len(text) <= n:
        return text
    return text[:n].rstrip() + "..."


def render_markdown(rows: list[dict]) -> str:
    parts = []
    parts.append("# Manual query review\n")
    parts.append(
        "Auto-generated by `eval/run_eval.py`. Fill in the **Score** field for each "
        "query after reading the answer and top citation.\n"
    )
    parts.append("**Scoring rubric:**\n")
    parts.append("- `good` — correct answer with valid citation")
    parts.append("- `partial` — roughly correct, weak citation, or paraphrased away from source")
    parts.append("- `wrong` — hallucinated section / invented case / contradicts the law")
    parts.append("- `abstain-correct` — said \"I cannot find...\" when corpus genuinely lacks the answer")
    parts.append("- `abstain-wrong` — said \"I cannot find...\" but the answer IS in the corpus\n")
    parts.append("---\n")

    for r in rows:
        parts.append(f"## {r['n']}. [{r['category']}] {r['query']}\n")
        parts.append(f"**Score:** _________\n")
        parts.append(
            f"**Abstained:** {r['abstained']}  |  **Top citation:** page {r['top_page']}  |  **HTTP:** {r['status']}\n"
        )
        parts.append("**Answer:**")
        parts.append(f"> {truncate(r['answer'], 600)}\n")
        if r['top_preview'] != "—":
            parts.append("**Top citation preview:**")
            parts.append(f"> {truncate(r['top_preview'], 300)}\n")
        parts.append("---\n")

    return "\n".join(parts)


async def main():
    base_url = "http://localhost:8000"
    timeout = 60.0

    rows = []
    print(f"\nRunning {len(QUERIES)} queries...\n")
    print(f"{'#':<3} {'cat':<14} {'cache':<5} {'http':<5} {'query':<55}")
    print("-" * 100)

    async with httpx.AsyncClient(base_url=base_url, timeout=timeout) as client:
        for i, (category, query) in enumerate(QUERIES, start=1):
            row = {
                "n": i,
                "category": category,
                "query": query,
                "answer": "",
                "top_page": "—",
                "top_preview": "—",
                "abstained": "n/a",
                "status": 0,
                "cached": False,
            }

            try:
                r = await client.post("/api/v1/query", json={"query": query})
                row["status"] = r.status_code

                if r.status_code == 200:
                    data = r.json()
                    answer = data.get("answer", "")
                    citations = data.get("citations", []) or []
                    metrics = data.get("metrics", {}) or {}

                    row["answer"] = answer
                    row["cached"] = bool(metrics.get("cache_hit", False))
                    row["abstained"] = "YES" if ABSTAIN_MARKER in answer.lower() else "no"

                    if citations:
                        top = citations[0]
                        row["top_page"] = str(top.get("page_number", "—"))
                        row["top_preview"] = top.get("content_preview", "—")
                else:
                    row["answer"] = f"HTTP {r.status_code}: {r.text[:200]}"

            except Exception as e:
                row["status"] = -1
                row["answer"] = f"{type(e).__name__}: {str(e)[:200]}"

            cache_label = "Y" if row["cached"] else "N"
            print(f"{i:<3} {category:<14} {cache_label:<5} {row['status']:<5} {query[:55]}")

            rows.append(row)

            if row["status"] == 200 and not row["cached"]:
                await asyncio.sleep(12)
            else:
                await asyncio.sleep(0.2)

    md = render_markdown(rows)
    OUT_PATH.write_text(md, encoding="utf-8")

    abstained = sum(1 for r in rows if r["abstained"] == "YES")
    success = sum(1 for r in rows if r["status"] == 200)
    failed = sum(1 for r in rows if r["status"] != 200)

    print("\n" + "=" * 60)
    print(f"Wrote {OUT_PATH}")
    print(f"Total: {len(rows)} | 200: {success} | failed: {failed} | abstained: {abstained}")
    print("=" * 60)
    print("\nNext step: open eval/manual_review.md and fill in the Score field for each query.\n")


if __name__ == "__main__":
    asyncio.run(main())
